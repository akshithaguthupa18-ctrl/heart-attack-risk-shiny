b <- readRDS('bundle.rds')
stopifnot(b$raw_rows==433323,b$n+b$excluded==b$raw_rows,b$train+b$validation+b$test==b$n)
stopifnot(all(is.finite(as.matrix(b$data[,names(b$medians)]))))
p <- data.frame(age=c(3,13),male=c(0,1),bmi=c(23,35),hypertension=c(0,1),cholesterol=c(0,1),diabetes=c(0,1),smoker=c(0,1),inactive=c(0,1))
prob <- as.numeric(predict(b$model,p,type='response'))
stopifnot(all(is.finite(prob)),all(prob>0 & prob<1),prob[2]>prob[1])
test <- b$data[b$split==3,]; pred <- as.numeric(predict(b$model,test,type='response'))
stopifnot(abs(mean((pred-test$heart_attack)^2)-b$metrics['Brier'])<1e-10)
stopifnot(sum(b$metrics[c('TP','FP','TN','FN')])==b$test)
cat('Data, model, probability and held-out Brier checks passed.\n')
